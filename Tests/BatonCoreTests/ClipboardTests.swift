import XCTest
@testable import BatonCore

final class ClipboardFilterTests: XCTestCase {
    func verdict(_ item: [String], also markers: [String] = []) -> ClipboardFilter.Verdict {
        ClipboardFilter.verdict(markers: item + markers, item: item)
    }

    func testPlainAndRichTextAreShared() {
        XCTAssertEqual(verdict(["public.utf8-plain-text"], also: ["NSStringPboardType"]), .share(["public.utf8-plain-text"]))
        let rich = ["public.rtf", "public.html", "com.apple.flat-rtfd", "com.apple.webarchive", "public.utf16-external-plain-text", "public.utf8-plain-text"]
        XCTAssertEqual(verdict(rich), .share(rich))
    }

    func testImagesAreShared() {
        XCTAssertEqual(verdict(["public.png"]), .share(["public.png"]))
        XCTAssertEqual(verdict(["public.jpeg", "public.heic", "com.compuserve.gif", "com.adobe.pdf"]), .share(["public.jpeg", "public.heic", "com.compuserve.gif", "com.adobe.pdf"]))
        XCTAssertEqual(verdict(["public.tiff"]), .share(["public.tiff"]))
    }

    func testTiffIsDroppedBesideACompressedImage() {
        XCTAssertEqual(verdict(["public.tiff", "public.png", "public.html"]), .share(["public.png", "public.html"]))
    }

    func testLinksKeepTheirURLAndTitle() {
        XCTAssertEqual(verdict(["public.url", "public.url-name", "public.utf8-plain-text"]), .share(["public.url", "public.url-name", "public.utf8-plain-text"]))
    }

    func testFilesAreNotShared() {
        // What Finder puts on the pasteboard for a copied file: the file, its name as text, its icon.
        XCTAssertEqual(verdict(["public.file-url", "public.utf8-plain-text", "com.apple.icns"], also: ["NSFilenamesPboardType"]), .skip(.files))
        XCTAssertEqual(verdict(["public.utf8-plain-text"], also: ["NSFilenamesPboardType"]), .skip(.files))
        XCTAssertEqual(verdict(["com.apple.pasteboard.promised-file-url", "public.png"]), .skip(.files))
    }

    func testSecretsAreNotShared() {
        XCTAssertEqual(verdict(["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]), .skip(.secret))
        XCTAssertEqual(verdict(["public.utf8-plain-text", "org.nspasteboard.TransientType"]), .skip(.secret))
        XCTAssertEqual(verdict(["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType"]), .skip(.secret))
        XCTAssertEqual(verdict(["public.utf8-plain-text", "com.agilebits.onepassword"]), .skip(.secret))
        // The marker counts wherever it is, also on a second item.
        XCTAssertEqual(verdict(["public.utf8-plain-text"], also: ["org.nspasteboard.ConcealedType"]), .skip(.secret))
    }

    func testWhatBatonOrHandoffWroteIsNotACopy() {
        XCTAssertEqual(verdict(["public.utf8-plain-text", ClipboardFilter.batonMarker]), .skip(.fromBaton))
        XCTAssertEqual(verdict(["public.utf8-plain-text", ClipboardFilter.handoffMarker]), .skip(.fromHandoff))
    }

    func testOtherAppsPrivateFormatsStayBehind() {
        XCTAssertEqual(verdict(["com.apple.iWork.TSPNativeData", "public.png", "public.utf8-plain-text"]), .share(["public.png", "public.utf8-plain-text"]))
        XCTAssertEqual(verdict(["com.example.private", "dyn.ah62d4rv4gu8y"]), .skip(.unsupported))
        XCTAssertEqual(verdict([]), .skip(.empty))
    }
}

final class ClipboardRegisterTests: XCTestCase {
    func text(_ string: String) -> [ClipboardPart] {
        [ClipboardPart(type: "public.utf8-plain-text", data: Data(string.utf8))]
    }

    func testACopyHereIsStampedAndBecomesCurrent() {
        var studio = ClipboardRegister(name: "studio", now: 1000)
        let content = studio.copied(text("a"), now: 2000)
        XCTAssertEqual(content?.stamp, ClipboardStamp(time: 2000, origin: "studio"))
        XCTAssertEqual(studio.current, content)
    }

    func testANewerCopyFromElsewhereIsAppliedAndAnOlderOneIgnored() {
        var studio = ClipboardRegister(name: "studio", now: 1000)
        let mine = studio.copied(text("mine"), now: 2000)!
        let older = ClipboardContent(stamp: ClipboardStamp(time: 1500, origin: "mini"), parts: text("older"))
        let newer = ClipboardContent(stamp: ClipboardStamp(time: 2500, origin: "mini"), parts: text("newer"))
        XCTAssertEqual(studio.receive(older, now: 2600), .ignore)
        XCTAssertEqual(studio.current, mine)
        XCTAssertEqual(studio.receive(newer, now: 2600), .apply)
        XCTAssertEqual(studio.receive(newer, now: 2700), .ignore)
        XCTAssertEqual(studio.current, newer)
    }

    func testACopyHereOutranksOneFromAMacWhoseClockIsAhead() {
        var studio = ClipboardRegister(name: "studio", now: 1000)
        let ahead = ClipboardContent(stamp: ClipboardStamp(time: 9000, origin: "mini"), parts: text("from the future"))
        XCTAssertEqual(studio.receive(ahead, now: 2000), .apply)
        let mine = studio.copied(text("mine"), now: 6000)!
        XCTAssertGreaterThan(mine.stamp, ahead.stamp)
    }

    func testTheSameContentRightAfterItWasSharedIsAnEcho() {
        var mbp = ClipboardRegister(name: "mbp", now: 1000)
        let remote = ClipboardContent(stamp: ClipboardStamp(time: 2000, origin: "studio"), parts: text("hello"))
        XCTAssertEqual(mbp.receive(remote, now: 2010), .apply)
        // Another program rewrites the pasteboard with what it just saw arrive.
        XCTAssertNil(mbp.copied(text("hello"), now: 2100))
        XCTAssertEqual(mbp.current, remote)
        // Copying the same text again later is a copy like any other.
        XCTAssertEqual(mbp.copied(text("hello"), now: 2010 + ClipboardRegister.echoWindowMs)?.stamp.origin, "mbp")
    }

    func testAnOlderSharedCopyDoesNotReplaceSomethingCopiedHereSince() {
        var mbp = ClipboardRegister(name: "mbp", now: 1000)
        // A file was copied here at 5000; files are not shared, but it is the newest thing here.
        mbp.changedWithoutSharing(now: 5000)
        let before = ClipboardContent(stamp: ClipboardStamp(time: 4000, origin: "studio"), parts: text("before"))
        XCTAssertEqual(mbp.receive(before, now: 6000), .adopt)
        XCTAssertEqual(mbp.current, before)
        let after = ClipboardContent(stamp: ClipboardStamp(time: 7000, origin: "studio"), parts: text("after"))
        XCTAssertEqual(mbp.receive(after, now: 7001), .apply)
    }

    func testWhatWasOnThePasteboardAtStartIsNotReplacedByAnOlderCopy() {
        var mini = ClipboardRegister(name: "mini", now: 5000)
        let old = ClipboardContent(stamp: ClipboardStamp(time: 3000, origin: "studio"), parts: text("old"))
        XCTAssertEqual(mini.receive(old, now: 5100), .adopt)
    }

    func testThisMacsOwnCopyComingBackIsNotWrittenAgain() {
        var studio = ClipboardRegister(name: "studio", now: 1000)
        let mine = ClipboardContent(stamp: ClipboardStamp(time: 2000, origin: "studio"), parts: text("mine"))
        XCTAssertEqual(studio.receive(mine, now: 2100), .adopt)
    }

    func testEveryMacSettlesOnTheSameCopyWhateverTheOrder() {
        let a = ClipboardContent(stamp: ClipboardStamp(time: 2000, origin: "mini"), parts: text("a"))
        let b = ClipboardContent(stamp: ClipboardStamp(time: 2000, origin: "mbp"), parts: text("b"))
        var first = ClipboardRegister(name: "studio", now: 1000)
        var second = ClipboardRegister(name: "studio", now: 1000)
        _ = first.receive(a, now: 2001)
        _ = first.receive(b, now: 2001)
        _ = second.receive(b, now: 2001)
        _ = second.receive(a, now: 2001)
        XCTAssertEqual(first.current, second.current)
        XCTAssertEqual(first.current, a)
    }

    func testCopiesStampedInTheSameMillisecondStillEndTheSameEverywhere() {
        var machines = ["studio", "mini", "mbp"].map { ClipboardRegister(name: $0, now: 1000) }
        let copies = machines.indices.map { machines[$0].copied(text(machines[$0].name), now: 2000)! }
        var onPasteboard = copies
        for index in machines.indices {
            for copy in copies.shuffled() where machines[index].receive(copy, now: 2001) == .apply {
                onPasteboard[index] = copy
            }
        }
        XCTAssertEqual(Set(machines.map { $0.current?.stamp }).count, 1)
        // What each Mac would paste is the copy its register holds.
        for index in machines.indices { XCTAssertEqual(onPasteboard[index], machines[index].current) }
    }

    func testDigestDependsOnTypesAndData() {
        let a = ClipboardContent.digest(of: [ClipboardPart(type: "ab", data: Data("c".utf8))])
        let b = ClipboardContent.digest(of: [ClipboardPart(type: "a", data: Data("bc".utf8))])
        XCTAssertNotEqual(a, b)
        XCTAssertEqual(a, ClipboardContent.digest(of: [ClipboardPart(type: "ab", data: Data("c".utf8))]))
    }

    func testSummaryNamesTypesAndSizesOnly() {
        let content = ClipboardContent(stamp: ClipboardStamp(time: 1, origin: "studio"), parts: text("top secret words"))
        XCTAssertEqual(content.summary, "public.utf8-plain-text 16 B")
    }
}

final class UniversalClipboardTests: XCTestCase {
    func testItIsOnUnlessTheSettingsSayOtherwise() {
        XCTAssertTrue(UniversalClipboard.isOn { _ in nil })
        XCTAssertFalse(UniversalClipboard.isOn { ["ActivityAdvertisingAllowed": false, "ActivityReceivingAllowed": false][$0] })
        XCTAssertTrue(UniversalClipboard.isOn { ["ActivityAdvertisingAllowed": true, "ActivityReceivingAllowed": true][$0] })
        // Half off still shares in one direction.
        XCTAssertTrue(UniversalClipboard.isOn { ["ActivityAdvertisingAllowed": false][$0] })
        XCTAssertTrue(UniversalClipboard.isOn { ["ActivityAdvertisingAllowed": false, "ActivityReceivingAllowed": true][$0] })
        // The hidden setting turns the clipboard off and leaves the rest of Handoff alone.
        XCTAssertFalse(UniversalClipboard.isOn { ["ClipboardSharingEnabled": false][$0] })
        XCTAssertTrue(UniversalClipboard.isOn { ["ClipboardSharingEnabled": true][$0] })
    }

    func testOneMacMayKeepItAndFromTwoUpTheClientsGiveItUp() {
        XCTAssertEqual(UniversalClipboard.turnOff(anchorOn: true, clientsOn: []), [])
        XCTAssertEqual(UniversalClipboard.turnOff(anchorOn: false, clientsOn: ["mini"]), [])
        XCTAssertEqual(UniversalClipboard.turnOff(anchorOn: false, clientsOn: []), [])
        XCTAssertEqual(UniversalClipboard.turnOff(anchorOn: true, clientsOn: ["mini"]), ["mini"])
        XCTAssertEqual(UniversalClipboard.turnOff(anchorOn: true, clientsOn: ["mini", "mbp"]), ["mbp", "mini"])
        XCTAssertEqual(UniversalClipboard.turnOff(anchorOn: false, clientsOn: ["mini", "mbp"]), ["mbp", "mini"])
    }

    func testWithNothingSetTheSystemSettingReadsAsAbsent() {
        // A domain nobody has written to, so nothing is created by asking.
        XCTAssertNil(UniversalClipboard.systemSetting("ActivityAdvertisingAllowed", domain: "com.xinding.baton.never-written"))
    }

    func testThePaneAndItsNameComeFromThisMacOS() {
        XCTAssertEqual(UniversalClipboard.settingsURL.scheme, "x-apple.systempreferences")
        XCTAssertTrue(UniversalClipboard.settingsPaneName.hasPrefix("AirDrop"))
        // The pane the link names is installed on this Mac under that identifier.
        let installed = Bundle(path: UniversalClipboard.settingsBundle)?.bundleIdentifier
        XCTAssertEqual(installed.map { "x-apple.systempreferences:\($0)" }, UniversalClipboard.settingsURL.absoluteString)
    }
}
