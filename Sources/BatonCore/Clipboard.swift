import CryptoKit
import Foundation
import UniformTypeIdentifiers

/// Orders copies made on different Macs: the copy with the greatest stamp is the shared clipboard.
public struct ClipboardStamp: Codable, Hashable, Comparable, Sendable {
    /// Milliseconds since 1970 on the Mac where the copy was made, pushed past every stamp that
    /// Mac had already seen, so a new copy always outranks what it replaces even if clocks differ.
    public var time: UInt64
    /// The Mac where the copy was made.
    public var origin: String

    public init(time: UInt64, origin: String) {
        self.time = time
        self.origin = origin
    }

    public static func < (a: ClipboardStamp, b: ClipboardStamp) -> Bool {
        a.time != b.time ? a.time < b.time : a.origin < b.origin
    }
}

/// One representation of what was copied, e.g. its plain text or its PNG.
public struct ClipboardPart: Equatable, Sendable {
    public var type: String
    public var data: Data

    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }
}

public struct ClipboardContent: Equatable, Sendable {
    public let stamp: ClipboardStamp
    public let parts: [ClipboardPart]
    /// SHA-256 over the types and their data: equal for equal content, whoever copied it.
    public let digest: Data

    public init(stamp: ClipboardStamp, parts: [ClipboardPart]) {
        self.init(stamp: stamp, parts: parts, digest: ClipboardContent.digest(of: parts))
    }

    init(stamp: ClipboardStamp, parts: [ClipboardPart], digest: Data) {
        self.stamp = stamp
        self.parts = parts
        self.digest = digest
    }

    public var byteCount: Int { parts.reduce(0) { $0 + $1.data.count } }

    /// Types and sizes, for the log. Never the data.
    public var summary: String {
        parts.map { "\($0.type) \(ClipboardContent.format(bytes: $0.data.count))" }.joined(separator: ", ")
    }

    public static func digest(of parts: [ClipboardPart]) -> Data {
        var hash = SHA256()
        func update(length: Int) {
            var n = UInt64(length).bigEndian
            withUnsafeBytes(of: &n) { hash.update(bufferPointer: $0) }
        }
        for part in parts {
            let type = Data(part.type.utf8)
            update(length: type.count)
            hash.update(data: type)
            update(length: part.data.count)
            hash.update(data: part.data)
        }
        return Data(hash.finalize())
    }

    public static func format(bytes: Int) -> String {
        if bytes < 1024 { return "\(bytes) B" }
        if bytes < 1024 * 1024 { return String(format: "%.1f KB", Double(bytes) / 1024) }
        return String(format: "%.1f MB", Double(bytes) / 1024 / 1024)
    }
}

/// Decides from the types on a pasteboard, without reading any data, whether a copy is shared
/// and which of its representations travel.
public enum ClipboardFilter {
    /// Baton adds this type to every clipboard it writes, so it never takes one for a new copy.
    public static let batonMarker = "com.xinding.baton.shared-clipboard"
    /// macOS adds this to a clipboard that arrived through Universal Clipboard (Handoff).
    public static let handoffMarker = "com.apple.is-remote-clipboard"

    public enum Skip: String, Equatable, Sendable {
        case empty
        /// Marked by its app as a password or as not meant to be kept.
        case secret
        case files
        case fromBaton
        case fromHandoff
        /// Nothing on it is text, rich text or an image.
        case unsupported
    }

    public enum Verdict: Equatable, Sendable {
        /// Share these types, in this order.
        case share([String])
        case skip(Skip)
    }

    /// The nspasteboard.org markers, and the older ones some password managers and text expanders set.
    static let secretMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping",
    ]

    static let fileMarkers: Set<String> = [
        "public.file-url", "NSFilenamesPboardType", "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-file-content-type", "com.apple.pasteboard.promised-file-name",
        "com.apple.NSFilePromiseItemMetaData", "Apple files promise pasteboard type", "NSPromiseContentsPboardType",
    ]

    /// Rich text and links whose types do not declare themselves as text.
    static let alsoShared: Set<String> = [
        "com.apple.flat-rtfd", "com.apple.webarchive", "public.url", "public.url-name", "com.adobe.pdf",
    ]

    static let tiff = "public.tiff"

    /// - Parameters:
    ///   - markers: every type anywhere on the pasteboard.
    ///   - item: the types of the first item, the one that is shared.
    public static func verdict(markers: [String], item: [String]) -> Verdict {
        let all = Set(markers).union(item)
        if all.isEmpty { return .skip(.empty) }
        if all.contains(batonMarker) { return .skip(.fromBaton) }
        if !all.isDisjoint(with: secretMarkers) { return .skip(.secret) }
        if all.contains(handoffMarker) { return .skip(.fromHandoff) }
        if !all.isDisjoint(with: fileMarkers) { return .skip(.files) }

        var shared = item.filter { isImage($0) || isText($0) }
        // A TIFF beside a compressed image is the same picture many times larger, and the
        // receiving pasteboard offers TIFF again by converting the compressed one.
        if shared.contains(where: { $0 != tiff && isImage($0) }) {
            shared.removeAll { $0 == tiff }
        }
        return shared.isEmpty ? .skip(.unsupported) : .share(shared)
    }

    static func isImage(_ type: String) -> Bool {
        type == "com.adobe.pdf" || UTType(type)?.conforms(to: .image) == true
    }

    static func isText(_ type: String) -> Bool {
        alsoShared.contains(type) || UTType(type)?.conforms(to: .text) == true
    }
}

/// What one Mac knows about the shared clipboard. Every Mac keeps the copy with the greatest
/// stamp, so all of them settle on the same one whatever order copies arrive in.
public struct ClipboardRegister {
    public let name: String
    /// The newest shared copy this Mac has seen.
    public private(set) var current: ClipboardContent?
    private var currentSince: UInt64 = 0
    /// The last change of this Mac's own pasteboard by a copy made here, shared or not. A copy
    /// from elsewhere replaces the pasteboard only if it outranks that.
    public private(set) var localChange: ClipboardStamp

    /// The same content appearing again this soon after it was shared is taken for an echo
    /// (another program rewriting the pasteboard), not for a new copy.
    public static let echoWindowMs: UInt64 = 3000

    public init(name: String, now: UInt64) {
        self.name = name
        localChange = ClipboardStamp(time: now, origin: name)
    }

    /// A copy made on this Mac. Returns the content to send to the others, or nil for an echo.
    public mutating func copied(_ parts: [ClipboardPart], now: UInt64) -> ClipboardContent? {
        let digest = ClipboardContent.digest(of: parts)
        if let current, current.digest == digest, max(now, currentSince) - min(now, currentSince) < ClipboardRegister.echoWindowMs {
            return nil
        }
        let time = max(now, (current?.stamp.time ?? 0) + 1)
        let content = ClipboardContent(stamp: ClipboardStamp(time: time, origin: name), parts: parts, digest: digest)
        current = content
        currentSince = now
        localChange = content.stamp
        return content
    }

    /// The pasteboard changed here but the copy is not shared (a file, a password, too large).
    /// It is still the newest thing on this Mac, so older copies from elsewhere must not replace it.
    public mutating func changedWithoutSharing(now: UInt64) {
        localChange = ClipboardStamp(time: max(now, current?.stamp.time ?? 0), origin: name)
    }

    public enum Reception: Equatable, Sendable {
        /// Newer than everything here: write it to the pasteboard.
        case apply
        /// The newest shared copy, but this Mac's own pasteboard holds something newer still,
        /// or the copy was made here in the first place.
        case adopt
        case ignore
    }

    public mutating func receive(_ content: ClipboardContent, now: UInt64) -> Reception {
        if let current, content.stamp <= current.stamp { return .ignore }
        let apply = content.stamp.origin != name && content.stamp > localChange
        current = content
        currentSince = now
        return apply ? .apply : .adopt
    }
}
